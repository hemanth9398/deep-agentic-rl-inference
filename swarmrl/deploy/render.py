"""Render the whole deployment for one profile into a directory of YAML files plus an install guide."""

from __future__ import annotations

from pathlib import Path

from swarmrl.deploy import fabric, inference, scheduling, training
from swarmrl.deploy.profile import DeployProfile
from swarmrl.parallel.planner import ClusterSpec, ModelSpec, Plan, TrainSpec, plan

HEADER = "# Generated by `swarmrl deploy render` from profile {name!r}. Edit the profile, not this file.\n"


def make_plan(p: DeployProfile) -> Plan:
    model = ModelSpec.load(p.planner_model)
    train = TrainSpec(seq_len=p.seq_len)
    cluster = ClusterSpec(nodes=p.train_nodes, gpus_per_node=p.gpus_per_node)
    if p.rollout == "pool":
        return plan(model, cluster, train, rollout_gpus=p.pool_gpus, context=p.seq_len)
    return plan(model, cluster, train, context=p.seq_len)


def namespaces(p: DeployProfile) -> list[dict]:
    out = [{"apiVersion": "v1", "kind": "Namespace", "metadata": {"name": ns}}
           for ns in (p.training_namespace, p.inference_namespace)]  # fmt: skip
    return out + training.sandbox_objects(p)


def render(p: DeployProfile, pl: Plan | None = None) -> dict[str, list[dict] | dict]:
    """{relative path: list of manifests (multi-doc YAML) or a single values/config dict}."""
    pl = pl or make_plan(p)
    files: dict[str, list[dict] | dict] = {
        "00-namespaces.yaml": namespaces(p),
        "10-fabric/sriov.yaml": fabric.sriov_objects(p, [p.training_namespace, p.inference_namespace]),
        "10-fabric/values/cilium.yaml": fabric.cilium_values(),
    }
    if p.scheduler == "kueue":
        files["20-scheduling/kueue.yaml"] = scheduling.kueue_objects(p)
        files["20-scheduling/values/kueue-manager-config.yaml"] = scheduling.kueue_configuration()
    else:
        files["20-scheduling/volcano.yaml"] = scheduling.volcano_objects(p)
        files["20-scheduling/volcano-scheduler-config.yaml"] = [scheduling.volcano_scheduler_config()]
    files["30-training/rbac.yaml"] = training.rbac_objects(p)
    files["30-training/swarmrl-config.yaml"] = [training.config_map(p)]
    files["30-training/rayjob.yaml"] = [training.rayjob(p, pl)]
    files["40-inference/gateway.yaml"] = inference.gateway_objects(p)
    files["40-inference/values/envoy-gateway.yaml"] = inference.envoy_gateway_values()
    if p.rollout == "pool":
        files["40-inference/rollout-pool.yaml"] = [inference.rollout_pool(p, pl)]
        files["40-inference/values/llm-d-router.yaml"] = inference.router_values(p)
    files["50-serving/llminferenceservice.yaml"] = [inference.llm_inference_service(p, pl)]
    return files


