def write(p: DeployProfile, out: str | Path) -> list[Path]:
    import yaml

    class Dumper(yaml.SafeDumper):
        def ignore_aliases(self, data):  # plain YAML: no &anchors for objects shared between manifests
            return True

    def text(dumper, data):  # embedded configs (EPP, scheduler, JSON settings) as readable block literals
        style = "|" if "\n" in data else None
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)

    Dumper.add_representer(str, text)

    out = Path(out)
    pl = make_plan(p)
    files = render(p, pl)
    written = []
    for rel, content in files.items():
        path = out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        docs = content if isinstance(content, list) else [content]
        body = "---\n".join(yaml.dump(d, Dumper=Dumper, sort_keys=False, width=120) for d in docs)
        path.write_text(HEADER.format(name=p.name) + body)
        written.append(path)
    guide = out / "README.md"
    guide.write_text(install_guide(p, pl, files))
    return [*written, guide]
