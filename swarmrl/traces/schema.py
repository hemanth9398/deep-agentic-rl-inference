"""The one trace schema: an eval trace and a training sample are the same object.

Three levels: Episode -> AgentSpan (one contiguous stretch of a role being active)
-> Transition (one LLM call). Transitions carry the exact token ids and log-probs
SGLang returned; nothing downstream re-tokenizes text.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from enum import StrEnum
from typing import Any


class Termination(StrEnum):
    SUBMIT = "submit"
    TURN_BUDGET = "turn_budget"
    TOKEN_BUDGET = "token_budget"
    CONTEXT_LIMIT = "context_limit"
    FORMAT_ERRORS = "format_errors"
    PING_PONG = "ping_pong"
    INFRA_ERROR = "infra_error"  # never scored against the model

    @property
    def scored(self) -> bool:
        return self is not Termination.INFRA_ERROR


class ErrorKind(StrEnum):
    NO_TOOL_CALL = "no_tool_call"
    BAD_JSON = "bad_json"
    UNKNOWN_TOOL = "unknown_tool"
    BAD_ARGS = "bad_args"
    TOOL_FAILED = "tool_failed"  # e.g. str_replace found no match
    REPEAT_CALL = "repeat_call"

    @property
    def is_format_error(self) -> bool:
        return self in (ErrorKind.NO_TOOL_CALL, ErrorKind.BAD_JSON, ErrorKind.UNKNOWN_TOOL, ErrorKind.BAD_ARGS)


@dataclass
class Transition:
    episode_id: str
    role: str
    turn: int  # episode-wide turn index
    role_turn: int  # turn index within this role's context
    input_ids: list[int]
    output_ids: list[int]
    rollout_logprobs: list[float]
    tool_call: dict[str, Any] | None = None
    observation: str = ""
    error_kind: str | None = None
    latency_s: float = 0.0
    finish_reason: str = "stop"
    # Ids appended after output_ids to close the turn when the server did not return them
    # (e.g. an end-of-turn token stripped by the server). Context only, never trained on.
    closing_ids: list[int] = field(default_factory=list)

    def __post_init__(self) -> None:
        if len(self.output_ids) != len(self.rollout_logprobs):
            raise ValueError(
                f"output_ids ({len(self.output_ids)}) and rollout_logprobs "
                f"({len(self.rollout_logprobs)}) must align token for token"
            )


@dataclass
class AgentSpan:
    role: str
    start_turn: int
    end_turn: int
    handoff_reason: str = ""  # tool that ended the span, or the termination
    handoff_to: str | None = None
    tokens_used: int = 0


@dataclass
class GradeSummary:
    resolved: bool = False
    f2p_passed: int = 0
    f2p_total: int = 0
    p2p_passed: int = 0
    p2p_total: int = 0
    apply_failed: bool = False
    failed_tests: list[str] = field(default_factory=list)


@dataclass
class Episode:
    episode_id: str
    task_id: str
    split: str
    swarm_fingerprint: str
    model_checkpoint: str
    seed: int
    termination: Termination = Termination.INFRA_ERROR
    team_reward: float | None = None
    grade: GradeSummary = field(default_factory=GradeSummary)
    protected_edits: list[str] = field(default_factory=list)  # excluded (protected) paths
    final_diff: str = ""
    spans: list[AgentSpan] = field(default_factory=list)
    transitions: list[Transition] = field(default_factory=list)
    repeat_calls: int = 0
    ping_pong_events: int = 0
    wall_time_s: float = 0.0
    group_id: str | None = None  # GRPO group (task + RL step)
    teacher: bool = False  # generated by a teacher model, not the student
    metadata: dict[str, Any] = field(default_factory=dict)

    @property
    def scored(self) -> bool:
        return self.termination.scored and self.team_reward is not None

    @property
    def resolved(self) -> bool:
        return self.grade.resolved and not self.protected_edits

    @property
    def submitted(self) -> bool:
        return self.termination is Termination.SUBMIT

    @property
    def num_turns(self) -> int:
        return len(self.transitions)

    def tokens_by_role(self) -> dict[str, int]:
        out: dict[str, int] = {}
        for t in self.transitions:
            out[t.role] = out.get(t.role, 0) + len(t.output_ids)
        return out

    def peak_context(self) -> int:
        return max((len(t.input_ids) + len(t.output_ids) for t in self.transitions), default=0)

    # --- serialization -------------------------------------------------------------

    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d["termination"] = self.termination.value
        return d

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> Episode:
        d = dict(d)
        d["termination"] = Termination(d["termination"])
        d["grade"] = GradeSummary(**d.get("grade", {}))
        d["spans"] = [AgentSpan(**s) for s in d.get("spans", [])]
        d["transitions"] = [Transition(**t) for t in d.get("transitions", [])]
        return cls(**d)

    def to_json(self) -> str:
        return json.dumps(self.to_dict())

    @classmethod
    def from_json(cls, s: str) -> Episode:
        return cls.from_dict(json.loads(s))

    def summary(self) -> dict[str, Any]:
        """The index row: everything except transitions and the diff."""
        return {
            "episode_id": self.episode_id,
            "task_id": self.task_id,
            "split": self.split,
            "swarm_fingerprint": self.swarm_fingerprint,
            "model_checkpoint": self.model_checkpoint,
            "seed": self.seed,
            "termination": self.termination.value,
            "team_reward": self.team_reward,
            "resolved": self.resolved,
            "num_turns": self.num_turns,
            "group_id": self.group_id,
            "teacher": self.teacher,
        }
